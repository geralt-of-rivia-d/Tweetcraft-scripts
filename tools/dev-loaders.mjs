#!/usr/bin/env node
// Generate Tampermonkey "dev loaders" in dev/: one per userscript, with the same metadata
// (match, grants, run-at, requires) but loading the code from your working copy through
// @require file:///..., so saving a file and reloading the game is enough to test a change.
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, listUserscripts, c } from './lib/common.mjs';

const DEV = join(ROOT, 'dev');
// Dropped: identity (replaced below) and update URLs (Tampermonkey must never "update" a loader).
const SKIP = new Set(['name', 'namespace', 'version', 'description', 'updateURL', 'downloadURL', 'installURL', 'supportURL', 'homepageURL']);

await rm(DEV, { recursive: true, force: true });
await mkdir(DEV, { recursive: true });

const scripts = await listUserscripts();
for (const s of scripts) {
  const local = pathToFileURL(s.path).href;
  const meta = [
    ['name', `${s.meta.get('name')} [DEV]`],
    ['namespace', `${s.meta.get('namespace')}.dev`],
    ['version', '0.0.0'],
    ['description', `DEV loader: runs ${s.file} straight from ${ROOT}`],
    ...s.meta.entries.filter(([k]) => !SKIP.has(k)),
    ['require', local], // after the script's own @requires, so its libraries load first
  ];
  const width = Math.max(...meta.map(([k]) => k.length)) + 2;
  const body = [
    '// ==UserScript==',
    ...meta.map(([k, v]) => `// @${k.padEnd(width - 1)}${v}`.trimEnd()),
    '// ==/UserScript==',
    '',
    `// Generated by \`npm run dev\`. The real code is ${s.file}, loaded via @require above.`,
    '// Disable the normal (non-DEV) copy of this script in Tampermonkey while this one is on.',
    '',
  ].join('\n');
  const out = join(DEV, s.file.replace(/(\.user)?\.js$/, '.dev.user.js'));
  await writeFile(out, body);
  console.log(`  ${c.green('+')} dev/${out.split(/[\\/]/).pop()}`);
}

console.log(`
${c.bold('One-time setup in Chrome')}
  1. chrome://extensions -> Tampermonkey -> Details -> turn on "Allow access to file URLs"
     (and "Allow User Scripts" if Chrome shows it).
  2. Install each loader you want: drag the file from the dev/ folder onto a Chrome window and
     click Install (or Tampermonkey dashboard -> Utilities -> Import from file).
  3. In the Tampermonkey dashboard, disable the normal copy of any script whose [DEV] copy is on,
     otherwise both run and patch the game twice.

${c.bold('Then')}: edit the .js file here, save, reload the game tab.
If an edit doesn't show up, set Tampermonkey Settings -> Externals -> Update interval to "Always".
Re-run ${c.bold('npm run dev')} after changing a script's metadata block (@grant, @match, @require ...).`);
